import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Store } from '../src/core/store.mjs';
import { Supervisor } from '../src/core/supervisor.mjs';
import { ControlledAdapter, STREAM } from '../test/helpers.mjs';
import { createDashboardServer } from '../src/server/http.mjs';

const require = createRequire(import.meta.url), { chromium } = require(process.env.AUTOCODEX_PLAYWRIGHT_MODULE || 'playwright');
const executablePath = [process.env.AUTOCODEX_BROWSER_PATH, chromium.executablePath(), join(process.env.ProgramFiles || '', 'Google', 'Chrome', 'Application', 'chrome.exe')].find(p => p && existsSync(p));
mkdirSync('.work', { recursive: true });
const directory = mkdtempSync(resolve('.work/ui-desktop-')), store = new Store(join(directory, 'guard')), adapter = new ControlledAdapter(); adapter.mode = 'codex';
const path = join(directory, 'thread.jsonl'); writeFileSync(path, JSON.stringify({ type: 'session_meta', payload: { id: 'desktop-thread' } }) + '\n');
adapter.threads.set('desktop-thread', { id: 'desktop-thread', path, cwd: directory, name: '原 Codex 项目任务', turns: [] });
adapter.readThreadSummary = id => adapter.readThread(id);
const supervisor = new Supervisor({ store, adapter }), http = createDashboardServer(supervisor, { port: 0 });
supervisor.setDefaults({ baseDelayMs: 10000, maxDelayMs: 10000, jitterRatio: 0 });
const task = await supervisor.existing.add({ threadId: 'desktop-thread' }), address = await http.listen();
let sequence = 0, events = [], browser;
const thread = { id: task.threadId, generation: 0, loaded: true, active: false, turnId: null, failedTurnId: null, pendingUser: 0, waiting: 0 };
const poll = () => supervisor.desktop.poll({ relayId: 'ui-relay', threads: [{ ...thread }], events: events.splice(0).map(event => ({ ...event, seq: ++sequence, threadId: task.threadId, generation: 0, at: Date.now() })) });
const timer = setInterval(() => void poll().catch(e => errors.push(e.message)), 200), errors = [], checks = [];
try {
  await poll(); browser = await chromium.launch({ executablePath, headless: true });
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1440, height: 1100 } }); context.setDefaultTimeout(10000);
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(address.launchPath).href); await page.locator('#desktop-assist').waitFor();
  assert.equal(await page.locator('#assist-continue').isChecked(), false);
  assert.equal(await page.locator('#assist-approve').isChecked(), false);
  await page.locator('#assist-continue').check(); await page.waitForFunction(() => !document.querySelector('#assist-continue').disabled);
  await page.locator('#assist-approve').check(); await page.waitForFunction(() => !document.querySelector('#assist-approve').disabled);
  await page.reload(); await page.locator('#desktop-assist').waitFor();
  assert(await page.locator('#assist-continue').isChecked()); assert(await page.locator('#assist-approve').isChecked());
  assert.equal(store.task(task.id).controlMode, 'observe'); assert.equal(adapter.sent.length, 0); checks.push('independent switches persist across reload without acquiring a writer');
  await page.locator('[data-view="settings"]').click(); await page.locator('#dnd-commonCommands').check();
  await page.waitForFunction(() => document.querySelector('#dnd-count').textContent.includes('1 / 5'));
  await page.locator('[data-view="monitor"]').click();
  thread.turnId = 'failed-turn'; thread.failedTurnId = thread.turnId;
  events.push({ type: 'started', turnId: thread.turnId }, { type: 'terminal', turnId: thread.turnId, status: 'failed', error: STREAM });
  await page.locator('#retry-banner').waitFor();
  assert((await page.locator('#desktop-assist-status').innerText()).includes('等待续发'));
  const before = await page.locator('#retry-message').innerText();
  await page.waitForFunction(value => document.querySelector('#retry-message').textContent !== value, before);
  checks.push('live relay failure, SSE update and retry countdown');
  await page.locator('#task-strategy').selectOption('new_session');
  await page.waitForFunction(() => !document.querySelector('#task-strategy').disabled);
  assert.equal(store.task(task.id).policy.strategy, 'new_session');
  await page.locator('#assist-continue').uncheck(); await page.locator('#retry-banner').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#desktop-assist-status').innerText(), '已连接');
  assert(store.task(task.id).assist.autoApprove); checks.push('disabling continuation cancels the plan independently of automatic approval');
  await page.locator('#assist-continue').check(); await page.waitForFunction(() => !document.querySelector('#assist-continue').disabled);
  await page.locator('#toast').waitFor({ state: 'hidden' });
  mkdirSync('docs/assets', { recursive: true });
  await page.screenshot({ path: 'docs/assets/desktop-monitor.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'docs/assets/desktop-monitor-narrow.png', fullPage: true });
  checks.push('1440px and 390px layouts, no horizontal overflow');
  await page.locator('#observation-toggle').click(); await page.waitForFunction(() => document.querySelector('#desktop-assist-status').textContent === '监测已停止');
  assert.equal(adapter.interrupted, undefined); checks.push('stopping observation does not interrupt the original conversation');
  assert.deepEqual(errors, []);
  const report = { testedAt: new Date().toISOString(), checks, browserErrors: errors, scope: 'isolated monitor fixture with real HTTP, SSE and browser; no model requests' };
  writeFileSync('docs/validation/desktop-panel-report.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2));
} finally { clearInterval(timer); await browser?.close(); await supervisor.close(); await http.close(); store.close(); }
